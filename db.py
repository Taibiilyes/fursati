def job_from_row(row):
    if not row:
        return None
    d = dict(row)
    d["requirements"] = json.loads(d.get("requirements") or "[]")
    return d


def user_from_row(row):
    if not row:
        return None
    d = dict(row)
    for k in ("skills", "languages", "certifications", "interests"):
        d[k] = json.loads(d.get(k) or "[]")
    d["experience"] = json.loads(d.get("experience") or "[]")
    d["education"] = json.loads(d.get("education") or "[]")
    return d
